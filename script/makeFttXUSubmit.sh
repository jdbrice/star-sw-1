#!/bin/sh
# Regenerate condor/submit_fttxu.txt -- FTT X-U / Y-V charge correlation with
# the geometric crossing gate, one job per MuDst.
#
#   sh script/makeFttXUSubmit.sh [nPerRun] [crossTol]
#
# Takes nPerRun files (default 2) from each day-081 run of DEV_fwd_test2. Those
# runs are all in Calibrations/ftt/fttDataWindowsB, which the job needs: it uses
# the per-VMM anchor AND window from the database. Spreading over runs rather
# than taking many files from one exercises many different per-run anchors.
set -u
TREE=/star/u/akio/fcstrk11/star-sw-fwd
OUT=/gpfs01/star/pwg_tasks/FwdCalib/akio/FttXU
BASE=/star/data2[0-9]/reco/production_pp500_2022/ReversedFullField/DEV_fwd_test2/2022/081
NPER=${1:-2}
TOL=${2:-10}
SUB=$TREE/condor/submit_fttxu.txt

mkdir -p $OUT/log
{
  echo "# FTT X-U / Y-V charge correlation with the geometric crossing gate."
  echo "#"
  echo "#   condor_submit condor/submit_fttxu.txt        <-- from OUTSIDE singularity"
  echo "#"
  echo "# One job per MuDst, $NPER file(s) from each day-081 run, so many different"
  echo "# per-run DB anchors are exercised rather than one run's. Per-VMM anchor AND"
  echo "# window come from Calibrations/ftt/fttDataWindowsB. Crossing tolerance $TOL mm."
  echo "# Merge:  hadd fttxu.root $OUT/st_fwd_*.root"
  echo "# Generated by script/makeFttXUSubmit.sh. Do not hand-edit; regenerate."
  echo ""
  echo "Executable   = /bin/env"
  echo "Universe     = vanilla"
  echo "notification = never"
  echo "getenv       = True"
  echo "Initialdir   = $TREE"
  echo "request_memory = 2000"
  for r in $(ls -d $BASE/*/ 2>/dev/null | sed 's|.*/\([0-9]*\)/$|\1|' | sort -u); do
    for f in $(ls $BASE/$r/*.MuDst.root 2>/dev/null | head -$NPER); do
      tag=$(basename $f .MuDst.root)
      echo ""
      echo "# $tag"
      echo "Arguments = \"singularity exec -e -B /direct -B /star -B /afs -B /gpfs -B /sdcc/lustre02 /cvmfs/star.sdcc.bnl.gov/containers/rhic_sl7.sif $TREE/script/runFttXU $f $OUT $TOL\""
      # separate Log/Output/Error: pointing all three at one file lets condor's
      # own event records clobber the job's stdout tail, which cost us the tail
      # of five jobs in the Run 22 calibration pass.
      echo "Log    = $OUT/log/$tag.log"
      echo "Output = $OUT/log/$tag.out"
      echo "Error  = $OUT/log/$tag.err"
      echo "Queue"
    done
  done
} > $SUB
echo "wrote $SUB -- $(grep -c '^Queue' $SUB) jobs"
