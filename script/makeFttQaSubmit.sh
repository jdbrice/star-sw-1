#!/bin/sh
# Build the condor submit file for a full-dataset FTT time-window calibration from
# the forward QA ROOT files -- one job per run, no MuDst read.
#
#   sh script/makeFttQaSubmit.sh [QADIR] [OUTDIR] [SUBMITFILE] [KEEPHIST]
#
# Defaults are the Run 22 set. Run this, then condor_submit the file it names,
# FROM OUTSIDE SINGULARITY.
set -e

QADIR=${1:-/gpfs/mnt/gpfs01/star/pwg/dkap7827/FcsPi0TssaData/21C0112/Output}
OUTDIR=${2:-/gpfs01/star/pwg_tasks/FwdCalib/akio/FttDataWindows22/data}
SUB=${3:-condor/submit_fttcal_qa_run22.txt}
KEEPHIST=${4:-0}

TOP=$(cd "$(dirname "$0")/.." && pwd)
LOGDIR=$OUTDIR/log

mkdir -p "$OUTDIR" "$LOGDIR" "$OUTDIR/qa"

cat > "$SUB" <<HDR
# FTT per-VMM time-window calibration for a whole dataset, from the forward QA
# ROOT files rather than from MuDsts.
#
#   condor_submit $SUB          <-- from OUTSIDE singularity
#
# Input  : $QADIR
#          StFwdRun22Qa_<run>_raw_<n>.root, one per run. Each holds
#          H2S_FttRawHit_dbcidVch_<vmm> for all 384 VMMs, 64 channels x 4096 dbcid.
# Output : $OUTDIR
#          fttDataWindow.<run>.txt per run, qa/<run>.qa per run, log/<run>.log.
#          empty/ holds the runs with no usable FTT data.
# Merge  : script/mergeFttCalQA.sh "$OUTDIR"
# Push   : root4star -l -b -q 'fttDataWindow_db.C(0,"writedb","$OUTDIR")'
#          -- DRY RUN FIRST, without "writedb".
#
# Generated by script/makeFttQaSubmit.sh. Do not hand-edit; regenerate.

Executable   = /bin/env
Universe     = vanilla
notification = never
getenv       = True
Initialdir   = $TOP

HDR

n=0
for f in "$QADIR"/StFwdRun22Qa_*_raw_*.root; do
    [ -e "$f" ] || continue
    b=$(basename "$f")
    # first 8-digit field; see the note in script/runfttcalqa about the prefix
    run=$(echo "$b" | awk '{ if (match($0,/[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]/)) print substr($0,RSTART,8) }')
    case "$run" in
        [0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]) ;;
        *) echo "skip (no run number): $b" >&2; continue ;;
    esac
    cat >> "$SUB" <<JOB
# run $run
Arguments = "singularity exec -e -B /direct -B /star -B /afs -B /gpfs -B /sdcc/lustre02 /cvmfs/star.sdcc.bnl.gov/containers/rhic_sl7.sif $TOP/script/runfttcalqa $f $OUTDIR $KEEPHIST"
Log    = $LOGDIR/$run.log
Output = $LOGDIR/$run.log
Error  = $LOGDIR/$run.log
Queue

JOB
    n=$((n+1))
done

echo "$SUB: $n jobs queued, one per run"
echo "output -> $OUTDIR"
echo "logs   -> $LOGDIR"
